#!/bin/bash
# Pins a built Splash child into the engine: writes
# Sources/SealedEngineV2/ChildPin.swift with the child's CD hash, its launch
# requirement bytes (A-13), the measured status word for this pair, and the
# canary decoy's CD hash. Rebuild the engine after a new child.
# Usage: scripts/pin-child.sh <signed child binary> <decoy binary> <reqgen tool> [status word]
set -eu
cd "$(dirname "$0")/.."
CHILD=$1; DECOY=$2; REQGEN=$3; WORD=${4:-0x22011311}
pin() { codesign -dvvv "$1" 2>&1 | awk -F= '/^CDHash=/{print $2}'; }
CP=$(pin "$CHILD"); DP=$(pin "$DECOY")
[ ${#CP} = 40 ] && [ ${#DP} = 40 ] || { echo "cannot read the CD hashes"; exit 1; }
T=$(mktemp); "$REQGEN" "$CHILD" "$CP" dummy "$T" > /dev/null
bytes() { python3 -c 'import sys; b=open(sys.argv[1],"rb").read() if len(sys.argv[1])!=40 else bytes.fromhex(sys.argv[1]); print(", ".join("0x%02x" % x for x in b))' "$1"; }
cat > Sources/SealedEngineV2/ChildPin.swift <<EOF
// Generated by scripts/pin-child.sh on $(date -u +%FT%TZ). Do not edit.
// Child: $(basename "$CHILD") CD hash $CP (measured status word $WORD on
// $(sysctl -n hw.model), macOS $(sw_vers -productVersion)). Decoy: $DP.
enum ChildPin {
    static let cdhash: [UInt8] = [$(bytes "$CP")]
    static let cdhashHex = "$CP"
    static let statusWord: UInt32 = $WORD
    static let requirement: [UInt8] = [$(bytes "$T")]
    static let decoyCDHash: [UInt8] = [$(bytes "$DP")]
}
EOF
rm -f "$T"
echo "pinned child $CP (decoy $DP) into Sources/SealedEngineV2/ChildPin.swift"
